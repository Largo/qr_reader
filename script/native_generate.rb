# frozen_string_literal: true

# Regenerates the qr_reader-native gem's C sources (native/ext/qr_reader_native)
# from the kernel files with Spinel. Run after changing anything under
# lib/qr_reader/kernels (or a file they require):
#
#   bundle exec rake native:generate      # SPINEL_HOME=~/workspace/spinel
#
# Steps: follow require_relative from lib/qr_reader/kernels.rb to find every
# kernel file; collect the "# spinel-sample: QrReaderKernels.name(args)"
# comments (one per entry point; they give Spinel the argument types); write
# native/lib/qr_reader_native/kernel.rb with a QrReaderNative wrapper per
# entry plus kernel_files / kernels_digest (checked by
# QrReader::NativeKernels at load time); run `spin ext build`.

require "digest"
require "fileutils"
require "open3"

ROOT = File.expand_path("..", __dir__)
LIB = File.join(ROOT, "lib")
NATIVE = File.join(ROOT, "native")
spin = File.join(ENV.fetch("SPINEL_HOME", File.expand_path("~/workspace/spinel")), "bin", "spin")
abort "spin not found at #{spin} (set SPINEL_HOME)" unless File.executable?(spin)

# Kernel files in require order, as paths relative to lib/.
def kernel_files(path, seen = [])
  rel = path.delete_prefix("#{LIB}/")
  return seen if seen.include?(rel)

  seen << rel
  File.read(path).scan(/^\s*require_relative\s+["']([^"']+)["']/) do |(target)|
    target += ".rb" unless target.end_with?(".rb")
    kernel_files(File.expand_path(target, File.dirname(path)), seen)
  end
  seen
end

def arity(args)
  return 0 if args.strip.empty?

  depth = 0
  count = 1
  in_string = nil
  prev = nil
  args.each_char do |c|
    if in_string
      in_string = nil if c == in_string && prev != "\\"
    else
      case c
      when '"', "'" then in_string = c
      when "(", "[", "{" then depth += 1
      when ")", "]", "}" then depth -= 1
      when "," then count += 1 if depth.zero?
      end
    end
    prev = c
  end
  count
end

files = kernel_files(File.join(LIB, "qr_reader", "kernels.rb"))
samples = files.flat_map do |rel|
  File.read(File.join(LIB, rel)).scan(/^\s*#\s*spinel-sample:\s*(QrReaderKernels\.(\w+)\((.*)\))\s*$/)
end
abort "no '# spinel-sample:' comments found in #{files.join(', ')}" if samples.empty?
names = samples.map { |_, name, _| name }
dups = names.select { |n| names.count(n) > 1 }.uniq
abort "duplicate samples for #{dups.join(', ')}" unless dups.empty?

sha = Digest::SHA256.new
files.each { |rel| sha << rel << "\0" << File.binread(File.join(LIB, rel)) << "\0" }
digest = sha.hexdigest

version = File.read(File.join(LIB, "qr_reader", "version.rb"))[/VERSION = "([^"]+)"/, 1]
pkg = File.join(NATIVE, "lib", "qr_reader_native")
FileUtils.mkdir_p(pkg)
kernel = +"# Generated by script/native_generate.rb from qr_reader #{version} - do not edit.\n"
kernel << "require_relative \"../../../lib/qr_reader/kernels\"\n\n"
kernel << "module QrReaderNative\n"
kernel << "  def self.kernels_digest\n    #{digest.inspect}\n  end\n\n"
kernel << "  def self.kernel_files\n    #{files.inspect}\n  end\n"
samples.each do |_, name, args|
  params = Array.new(arity(args)) { |i| "a#{i}" }.join(", ")
  kernel << "\n  def self.#{name}(#{params})\n    QrReaderKernels.#{name}(#{params})\n  end\n"
end
kernel << "end\n\nif __FILE__ == $0\n  p QrReaderNative.kernels_digest\n  p QrReaderNative.kernel_files\n"
samples.each { |_, name, args| kernel << "  p QrReaderNative.#{name}(#{args})\n" }
kernel << "end\n"
File.write(File.join(pkg, "kernel.rb"), kernel)

File.write(File.join(NATIVE, "spin.toml"), <<~TOML)
  # Generated by script/native_generate.rb - do not edit.
  [package]
  name = "qr_reader_native"
  version = "#{version}"

  [ext]
  module = "QrReaderNative"
  entries = [#{(%w[kernels_digest kernel_files] + names).map { |n| "\"QrReaderNative.#{n}\"" }.join(', ')}]
TOML

ext = File.join(NATIVE, "ext", "qr_reader_native")
FileUtils.mkdir_p(ext)
Dir.chdir(NATIVE) do
  log, status = Open3.capture2e(spin, "ext", "build")
  puts log.lines.grep_v(/\AWrote /).join
  abort "spin ext build failed" unless status.success?
end
spinel_version, = Open3.capture2(File.join(File.dirname(spin), "spinel"), "--version")
File.write(File.join(ext, "SPINEL_VERSION"), spinel_version)
puts "native/ext/qr_reader_native regenerated: #{names.size} entries, #{files.size} kernel files, digest #{digest[0, 12]}"
