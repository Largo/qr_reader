"""Writes lib/qr_reader/formats/pdf/font_tables.rb: the glyph name tables PDF
font handling needs (CFF standard strings, StandardEncoding, MacRomanEncoding,
WinAnsiEncoding, and Unicode values of the names in them), from fontTools.
Development tool only:

    python -I script/generate_font_tables.py
"""
import os

from fontTools import agl
from fontTools.cffLib import cffStandardStrings
from fontTools.encodings.MacRoman import MacRoman
from fontTools.encodings.StandardEncoding import StandardEncoding

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "lib", "qr_reader", "formats", "pdf", "font_tables.rb")


def win_ansi():
    names = [".notdef"] * 256
    for code in range(32, 256):
        try:
            ch = bytes([code]).decode("cp1252")
        except UnicodeDecodeError:
            names[code] = "bullet"  # PDF 32000-1 Annex D: unused codes show a bullet
            continue
        names[code] = agl.UV2AGL.get(ord(ch), "uni%04X" % ord(ch))
    names[0x7F] = "bullet"
    names[0xA0] = "space"
    names[0xAD] = "hyphen"
    return names


def ruby_names(names, per_line=8):
    items = ["nil" if n == ".notdef" else '"%s"' % n for n in names]
    lines = []
    for i in range(0, len(items), per_line):
        lines.append("          " + ", ".join(items[i:i + per_line]) + ",")
    return "\n".join(lines)


def main():
    standard = list(StandardEncoding)
    mac = list(MacRoman)
    win = win_ansi()
    used = set(n for n in standard + mac + win if n != ".notdef")
    unicode = {}
    for name in sorted(used):
        uv = agl.AGL2UV.get(name)
        if uv is None and name.startswith("uni") and len(name) == 7:
            uv = int(name[3:], 16)
        if uv is not None:
            unicode[name] = uv
    uni_items = ['"%s" => 0x%04X' % (n, unicode[n]) for n in sorted(unicode)]
    uni_lines = "\n".join("          " + ", ".join(uni_items[i:i + 5]) + "," for i in range(0, len(uni_items), 5))
    strings = list(cffStandardStrings)
    assert len(strings) == 391
    with open(OUT, "w", newline="\n") as f:
        f.write("""# frozen_string_literal: true

# Generated by script/generate_font_tables.py from fontTools (MIT); do not edit.
module QrReader
  module Formats
    module PDF
      # Glyph name tables for PDF fonts: Adobe's standard encodings, the CFF
      # standard strings and the Unicode values of the glyph names in them.
      module FontTables
        # SID -> name for SIDs 0..390 of CFF fonts.
        CFF_STANDARD_STRINGS = [
%s
        ].freeze

        # Code -> glyph name (nil: .notdef).
        STANDARD_ENCODING = [
%s
        ].freeze

        MAC_ROMAN_ENCODING = [
%s
        ].freeze

        WIN_ANSI_ENCODING = [
%s
        ].freeze

        # Glyph name -> Unicode code point (Adobe Glyph List).
        UNICODE = {
%s
        }.freeze
      end
    end
  end
end
""" % (ruby_names(strings), ruby_names(standard), ruby_names(mac), ruby_names(win), uni_lines))
    print("wrote", OUT)


main()
