# frozen_string_literal: true

# Builds a CRuby extension from qr_reader kernel files with Spinel (dev tool).
#
#   ruby script/spinel_ext.rb OUT_DIR \
#     --require lib/qr_reader/kernels/png.rb \
#     --sample 'QrReaderKernels.png_unfilter("\x00\x01".b, 1, 1, 1)' [--sample ...]
#
# Every --sample is a call of a QrReaderKernels entry with arguments of the
# types it is used with: Spinel infers the entry's signature from it (the
# sample is never run when the extension is loaded). For each sampled entry
# the extension defines QrReaderNative.<name> (same arguments, same result;
# Strings come back tagged UTF-8 - use .b), so native and pure Ruby kernels
# can be compared side by side in one process:
#
#   require "qr_reader"; require "OUT_DIR/ext/qr_reader_native/qr_reader_native.so"
#   QrReaderNative.png_unfilter(raw, 1, 1, 1).b == QrReaderKernels.png_unfilter(raw, 1, 1, 1)
#
# Needs a Spinel checkout (SPINEL_HOME, default ~/workspace/spinel) and a C
# compiler. The C build uses `make -j2` (MAKE_JOBS) to keep memory use low.

require "fileutils"
require "optparse"
require "open3"
require "pathname"

ROOT = File.expand_path("..", __dir__)
spinel_home = ENV.fetch("SPINEL_HOME", File.expand_path("~/workspace/spinel"))
spin = File.join(spinel_home, "bin", "spin")
requires = []
samples = []
OptionParser.new do |o|
  o.banner = "Usage: ruby script/spinel_ext.rb OUT_DIR --require FILE... --sample CALL..."
  o.on("--require FILE", "kernel file (relative to the repository)") { |f| requires << f }
  o.on("--sample CALL", "typed sample call of a QrReaderKernels entry") { |s| samples << s }
end.parse!
out = ARGV.shift or abort("OUT_DIR missing")
abort "no --sample given" if samples.empty?
abort "spin not found at #{spin} (set SPINEL_HOME)" unless File.executable?(spin)

entries = samples.map do |call|
  m = call.match(/\AQrReaderKernels\.(\w+)\((.*)\)\s*\z/m) or abort("sample must look like QrReaderKernels.name(args): #{call}")
  [m[1], m[2]]
end

out = File.expand_path(out)
pkg = File.join(out, "lib", "qr_reader_native")
FileUtils.mkdir_p(pkg)
rel = ->(path) { Pathname.new(File.join(ROOT, path)).relative_path_from(Pathname.new(pkg)).to_s }

kernel = +"# Generated by script/spinel_ext.rb - do not edit.\n"
requires.each { |f| kernel << "require_relative #{rel.call(f.sub(/\.rb\z/, '')).inspect}\n" }
kernel << "\nmodule QrReaderNative\n"
entries.each do |name, args|
  # Arity from the sample: count top-level commas.
  depth = 0
  count = args.strip.empty? ? 0 : 1
  args.each_char do |c|
    case c
    when "(", "[", "{" then depth += 1
    when ")", "]", "}" then depth -= 1
    when "," then count += 1 if depth.zero?
    end
  end
  params = Array.new(count) { |i| "a#{i}" }.join(", ")
  kernel << "  def self.#{name}(#{params})\n    QrReaderKernels.#{name}(#{params})\n  end\n\n"
end
kernel << "end\n\nif __FILE__ == $0\n"
entries.each { |name, args| kernel << "  p QrReaderNative.#{name}(#{args})\n" }
kernel << "end\n"
File.write(File.join(pkg, "kernel.rb"), kernel)
File.write(File.join(out, "spin.toml"), <<~TOML)
  [package]
  name = "qr_reader_native"
  version = "0.0.0"

  [ext]
  module = "QrReaderNative"
  entries = [#{entries.map { |n, _| "\"QrReaderNative.#{n}\"" }.join(', ')}]
TOML

ext = File.join(out, "ext", "qr_reader_native")
FileUtils.mkdir_p(ext)
File.write(File.join(ext, "extconf.rb"), <<~RUBY)
  require "mkmf"
  $INCFLAGS << " -I$(srcdir)"
  create_makefile("qr_reader_native/qr_reader_native")
RUBY

Dir.chdir(out) do
  t0 = Process.clock_gettime(Process::CLOCK_MONOTONIC)
  log, status = Open3.capture2e(spin, "ext", "build")
  puts log.lines.grep_v(/\AWrote /).join
  abort "spin ext build failed" unless status.success?
  Dir.chdir(ext) do
    log, status = Open3.capture2e(RbConfig.ruby, "extconf.rb")
    abort log unless status.success?
    log, status = Open3.capture2e("make", "-j#{ENV.fetch('MAKE_JOBS', '2')}")
    abort log.lines.last(30).join unless status.success?
  end
  so = Dir[File.join(ext, "*.{so,bundle,dll}")].first
  printf("built %s in %.0f s\n", so, Process.clock_gettime(Process::CLOCK_MONOTONIC) - t0)
end
